/**
 * errorMapper のユニットテスト
 *
 * 対象: mapErrorToMessage(errorCode, defaultMessage?)
 * 検証: エラーコード（E1xxx〜E9xxx）→ 日本語メッセージへの変換
 */

import { mapErrorToMessage, ERROR_MESSAGE_MAP } from '../errorUtils';

describe('mapErrorToMessage', () => {
  // ─────────────────────────────────────────────
  // E1xxx: CLIENT
  // ─────────────────────────────────────────────
  describe('E1xxx: CLIENT エラー', () => {
    test.each([
      ['E1001', 'ファイルサイズが上限を超えています'],
      ['E1002', 'ファイル形式が正しくありません'],
      ['E1003', '入力内容に誤りがあります'],
      ['E1004', '必須項目が入力されていません'],
      ['E1005', '入力形式が正しくありません'],
      ['E1006', 'フォルダ名が正しくありません'],
      ['E1007', 'サブフォルダ名が正しくありません'],
      ['E1008', 'コンテンツ形式が正しくありません'],
      ['E1009', 'フォーマット名が指定されていません'],
    ])('%s → %s', (code, expected) => {
      expect(mapErrorToMessage(code)).toBe(expected);
    });
  });

  // ─────────────────────────────────────────────
  // E2xxx: DATA
  // ─────────────────────────────────────────────
  describe('E2xxx: DATA エラー', () => {
    test.each([
      ['E2001', 'XMLの解析に失敗しました'],
      ['E2002', 'データ形式が正しくありません'],
      ['E2003', 'データの読み込みに失敗しました'],
      ['E2004', 'データの保存に失敗しました'],
    ])('%s → %s', (code, expected) => {
      expect(mapErrorToMessage(code)).toBe(expected);
    });
  });

  // ─────────────────────────────────────────────
  // E3xxx: NETWORK
  // ─────────────────────────────────────────────
  describe('E3xxx: NETWORK エラー', () => {
    test.each([
      ['E3001', 'サーバーに接続できません。ネットワークを確認してください'],
      ['E3002', 'リクエストがタイムアウトしました。再度お試しください'],
      ['E3003', 'ネットワークエラーが発生しました。接続を確認してください'],
    ])('%s → %s', (code, expected) => {
      expect(mapErrorToMessage(code)).toBe(expected);
    });
  });

  // ─────────────────────────────────────────────
  // E4xxx: SERVER
  // ─────────────────────────────────────────────
  describe('E4xxx: SERVER エラー', () => {
    test.each([
      ['E4001', 'サーバー内部エラーが発生しました。管理者にお問い合わせください'],
      ['E4002', 'データベースエラーが発生しました。管理者にお問い合わせください'],
      ['E4003', 'メール送信に失敗しました。しばらくしてから再度お試しください'],
      ['E4004', 'セッション生成に失敗しました。再度ログインしてください'],
      ['E4005', 'システムエラーが発生しました。管理者にお問い合わせください'],
      ['E4006', 'ストレージエラーが発生しました。管理者にお問い合わせください'],
    ])('%s → %s', (code, expected) => {
      expect(mapErrorToMessage(code)).toBe(expected);
    });
  });

  // ─────────────────────────────────────────────
  // E5xxx: AUTH
  // ─────────────────────────────────────────────
  describe('E5xxx: AUTH エラー', () => {
    test.each([
      ['E5001', 'ユーザー名またはパスワードが正しくありません'],
      ['E5002', 'セッションの有効期限が切れました。再度ログインしてください'],
      ['E5003', 'PINコードが正しくありません'],
      ['E5004', 'PINコードの有効期限が切れました。再送信してください'],
      ['E5005', 'PINコード入力試行回数の上限に達しました。最初からやり直してください'],
      ['E5006', 'アカウントが無効化されています。管理者にお問い合わせください'],
      ['E5007', 'ログイン試行回数が上限に達しました。しばらくしてから再度お試しください'],
      ['E5008', 'PINコード再送信回数が上限に達しました。しばらくしてから再度お試しください'],
      ['E5009', 'パスワードリセットトークンが正しくありません'],
      ['E5010', 'パスワードリセットトークンの有効期限が切れています'],
      ['E5011', 'パスワードリセットトークンは既に使用済みです'],
      ['E5012', 'アクセスが拒否されました'],
      ['E5013', '認証が必要です。再度ログインしてください'],
      ['E5014', 'セッションの有効期限が切れました。再度ログインしてください'],
      ['E5015', 'この操作を行う権限がありません'],
    ])('%s → %s', (code, expected) => {
      expect(mapErrorToMessage(code)).toBe(expected);
    });
  });

  // ─────────────────────────────────────────────
  // E6xxx: RESOURCE
  // ─────────────────────────────────────────────
  describe('E6xxx: RESOURCE エラー', () => {
    test.each([
      ['E6001', '指定されたリソースが見つかりません'],
      ['E6002', '指定されたファイルが見つかりません'],
      ['E6003', '指定されたフォルダが見つかりません'],
      ['E6004', '親フォルダが見つかりません'],
      ['E6005', '同名のファイルが既に存在します'],
      ['E6006', '同名のフォルダが既に存在します'],
    ])('%s → %s', (code, expected) => {
      expect(mapErrorToMessage(code)).toBe(expected);
    });
  });

  // ─────────────────────────────────────────────
  // E7xxx: BUSINESS
  // ─────────────────────────────────────────────
  describe('E7xxx: BUSINESS エラー', () => {
    test.each([
      ['E7001', '同じ名前のプロジェクトが既に存在します'],
      ['E7002', 'プロジェクトは現在チェックアウト中です'],
      ['E7003', 'MAIMLファイルが登録されていません'],
      ['E7004', '既に確認済みです'],
      ['E7005', 'プロジェクトの状態が正しくありません'],
      ['E7006', 'プロジェクトの指示が見つかりません'],
      ['E7007', 'タスクは現在作業中です'],
      ['E7008', '指定されたタスクまたはメソッドが見つかりません'],
    ])('%s → %s', (code, expected) => {
      expect(mapErrorToMessage(code)).toBe(expected);
    });
  });

  // ─────────────────────────────────────────────
  // E9xxx: UNKNOWN
  // ─────────────────────────────────────────────
  describe('E9xxx: UNKNOWN エラー', () => {
    test('E9999 → デフォルトのエラーメッセージ', () => {
      expect(mapErrorToMessage('E9999')).toBe(
        'エラーが発生しました。しばらくしてから再度お試しください'
      );
    });
  });

  // ─────────────────────────────────────────────
  // フォールバック・エッジケース
  // ─────────────────────────────────────────────
  describe('フォールバック・エッジケース', () => {
    test('未知のコードはデフォルトメッセージを返す', () => {
      expect(mapErrorToMessage('E9998')).toBe(
        'エラーが発生しました。しばらくしてから再度お試しください'
      );
    });

    test('マッピング外のコードも同様にデフォルトを返す', () => {
      expect(mapErrorToMessage('UNKNOWN_CODE')).toBe(
        'エラーが発生しました。しばらくしてから再度お試しください'
      );
    });

    test('空文字列はデフォルトメッセージを返す', () => {
      expect(mapErrorToMessage('')).toBe(
        'エラーが発生しました。しばらくしてから再度お試しください'
      );
    });

    test('null はデフォルトメッセージを返す', () => {
      expect(mapErrorToMessage(null as any)).toBe(
        'エラーが発生しました。しばらくしてから再度お試しください'
      );
    });

    test('undefined はデフォルトメッセージを返す', () => {
      expect(mapErrorToMessage(undefined as any)).toBe(
        'エラーが発生しました。しばらくしてから再度お試しください'
      );
    });

    test('第2引数でカスタムデフォルトメッセージを指定できる', () => {
      expect(mapErrorToMessage('UNKNOWN_CODE', 'カスタムエラー')).toBe('カスタムエラー');
    });

    test('ERROR_MESSAGE_MAP のすべてのコードが文字列メッセージを持つ', () => {
      for (const [code, message] of Object.entries(ERROR_MESSAGE_MAP)) {
        expect(typeof message).toBe('string');
        expect(message.length).toBeGreaterThan(0);
        // コードは E + 数字 4桁 の形式
        expect(code).toMatch(/^E\d{4}$/);
      }
    });
  });
});
